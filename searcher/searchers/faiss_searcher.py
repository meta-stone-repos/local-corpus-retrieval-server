"""
FAISS searcher implementation for dense retrieval.
"""

import glob
import logging
import os
import pickle
from itertools import chain
from typing import Any, Dict, List, Optional

import faiss
import numpy as np
import torch
from datasets import load_dataset
from tevatron.retriever.arguments import ModelArguments
from tevatron.retriever.driver.encode import DenseModel
from tevatron.retriever.searcher import FaissFlatSearcher
from tqdm import tqdm
from transformers import AutoModel, AutoTokenizer

from .base import BaseSearcher
from .document_store import SQLiteDocumentStore

logger = logging.getLogger(__name__)


class _FaissIndexAdapter:
    """Small adapter so pre-built FAISS indexes expose the same search surface
    as Tevatron's ``FaissFlatSearcher``.
    """

    def __init__(self, index):
        self.index = index

    def search(self, q_reps: np.ndarray, k: int):
        q_reps = np.asarray(q_reps, dtype=np.float32)
        return self.index.search(q_reps, k)


class FaissSearcher(BaseSearcher):
    @classmethod
    def parse_args(cls, parser):
        parser.add_argument(
            "--index-path",
            required=False,
            help=(
                "For index_type=flat: glob pattern for Tevatron pickle shards. "
                "For ANN indexes: path to a pre-built FAISS index file. "
                "Required unless --corpus supplies it via a manifest."
            ),
        )
        parser.add_argument(
            "--index-type",
            choices=["flat", "ivf-flat"],
            default="flat",
            help="Dense index backend (default: flat).",
        )
        parser.add_argument(
            "--lookup-path",
            default=None,
            help="docid lookup pickle for a pre-built ANN index. Loaded from the corpus manifest when available.",
        )
        parser.add_argument(
            "--nprobe",
            type=int,
            default=32,
            help="Number of IVF lists probed per query for ivf-flat indexes (default: 32).",
        )
        parser.add_argument(
            "--model-name",
            required=False,
            help="Model name for FAISS search (e.g. 'Qwen/Qwen3-Embedding-0.6B'). Required unless --corpus supplies it via a manifest.",
        )
        parser.add_argument(
            "--normalize",
            action="store_true",
            default=False,
            help="Whether to normalize embeddings for FAISS search (default: False)",
        )
        parser.add_argument(
            "--pooling",
            default="eos",
            help="Pooling method for FAISS search (default: eos)",
        )
        parser.add_argument(
            "--torch-dtype",
            default="float16",
            choices=["float16", "bfloat16", "float32"],
            help="Torch dtype for FAISS search (default: float16)",
        )
        parser.add_argument(
            "--dataset-name",
            default="Tevatron/browsecomp-plus-corpus",
            help="Dataset name for document retrieval in FAISS search (default: Tevatron/browsecomp-plus-corpus)",
        )
        parser.add_argument(
            "--corpus-path",
            default=None,
            help="Optional local JSON/JSONL corpus for docid->text lookup. Prefer --document-store for large corpora.",
        )
        parser.add_argument(
            "--document-store",
            default=None,
            help="Optional local SQLite document store generated by build_corpus.py. Avoids loading the full corpus into RAM.",
        )
        parser.add_argument(
            "--task-prefix",
            default="Instruct: Given a web search query, retrieve relevant passages that answer the query\nQuery:",
            help="Task prefix for FAISS search queries",
        )
        parser.add_argument(
            "--max-length",
            type=int,
            default=8192,
            help="Maximum sequence length for FAISS search (default: 8192)",
        )

    def __init__(self, args):
        if not args.model_name:
            raise ValueError("model_name is required for FAISS searcher (or provide --corpus with a dense manifest)")
        if args.model_name == "bm25":
            raise ValueError("model_name cannot be 'bm25' for FAISS searcher")
        if not args.index_path:
            raise ValueError("index_path is required for FAISS searcher (or provide --corpus with a dense manifest)")

        self.args = args
        self.retriever = None
        self.model = None
        self.tokenizer = None
        self.lookup = None
        self.docid_to_text = None
        self.docid_to_metadata = None
        self.document_store = None

        logger.info("Initializing FAISS searcher...")

        self._load_faiss_index()

        self._load_model()

        self._load_document_source()

        logger.info("FAISS searcher initialized successfully")

    def _load_faiss_index(self) -> None:
        if self.args.index_type == "flat":
            self._load_flat_index()
        elif self.args.index_type == "ivf-flat":
            self._load_prebuilt_ivf_index()
        else:
            raise ValueError(f"Unsupported FAISS index type: {self.args.index_type}")

        self._setup_gpu()

    def _load_flat_index(self) -> None:
        def pickle_load(path):
            with open(path, "rb") as f:
                reps, lookup = pickle.load(f)
            return np.asarray(reps, dtype=np.float32), lookup

        index_files = sorted(glob.glob(self.args.index_path))
        logger.info(
            f"Pattern match found {len(index_files)} files; loading Flat index."
        )

        if not index_files:
            raise ValueError(f"No files found matching pattern: {self.args.index_path}")

        p_reps_0, p_lookup_0 = pickle_load(index_files[0])
        self.retriever = FaissFlatSearcher(p_reps_0)

        shards = chain([(p_reps_0, p_lookup_0)], map(pickle_load, index_files[1:]))
        if len(index_files) > 1:
            shards = tqdm(
                shards, desc="Loading shards into index", total=len(index_files)
            )

        self.lookup = []
        for p_reps, p_lookup in shards:
            self.retriever.add(p_reps)
            self.lookup += list(p_lookup)

        logger.info(f"Flat index ready: {len(self.lookup):,} vectors")

    def _load_prebuilt_ivf_index(self) -> None:
        index_path = self.args.index_path
        if not os.path.isfile(index_path):
            raise ValueError(f"FAISS ANN index not found: {index_path}")
        if not self.args.lookup_path or not os.path.isfile(self.args.lookup_path):
            raise ValueError(
                "lookup_path is required for ivf-flat and must point to the "
                "lookup pickle generated by build_corpus.py"
            )

        logger.info(f"Loading pre-built IVF-Flat index: {index_path}")
        index = faiss.read_index(index_path)

        if hasattr(index, "nprobe"):
            nprobe = max(1, int(self.args.nprobe))
            if hasattr(index, "nlist"):
                nprobe = min(nprobe, int(index.nlist))
            index.nprobe = nprobe
            logger.info(
                f"IVF parameters: nlist={getattr(index, 'nlist', 'unknown')}, "
                f"nprobe={index.nprobe}"
            )

        with open(self.args.lookup_path, "rb") as f:
            self.lookup = list(pickle.load(f))

        if int(index.ntotal) != len(self.lookup):
            raise ValueError(
                f"ANN index/lookup size mismatch: index.ntotal={index.ntotal}, "
                f"lookup={len(self.lookup)}"
            )

        self.retriever = _FaissIndexAdapter(index)
        logger.info(f"IVF-Flat index ready: {len(self.lookup):,} vectors")

    def _setup_gpu(self) -> None:
        num_gpus = faiss.get_num_gpus()
        if num_gpus == 0:
            logger.info("No GPU found or using faiss-cpu. Using CPU.")
        else:
            logger.info(f"Using {num_gpus} GPU(s)")
            if num_gpus == 1:
                co = faiss.GpuClonerOptions()
                co.useFloat16 = True
                res = faiss.StandardGpuResources()
                self.retriever.index = faiss.index_cpu_to_gpu(
                    res, 0, self.retriever.index, co
                )
            else:
                co = faiss.GpuMultipleClonerOptions()
                co.shard = True
                co.useFloat16 = True
                self.retriever.index = faiss.index_cpu_to_all_gpus(
                    self.retriever.index, co, ngpu=num_gpus
                )

    def _load_model(self) -> None:
        logger.info(f"Loading model: {self.args.model_name}")

        hf_home = os.getenv("HF_HOME")
        if hf_home:
            cache_dir = hf_home
        else:
            cache_dir = None

        model_args = ModelArguments(
            model_name_or_path=self.args.model_name,
            normalize=self.args.normalize,
            pooling=self.args.pooling,
            cache_dir=cache_dir,
        )

        if self.args.torch_dtype == "float16":
            torch_dtype = torch.float16
        elif self.args.torch_dtype == "bfloat16":
            torch_dtype = torch.bfloat16
        else:
            torch_dtype = torch.float32

        self.model = DenseModel.load(
            model_args.model_name_or_path,
            pooling=model_args.pooling,
            normalize=model_args.normalize,
            lora_name_or_path=model_args.lora_name_or_path,
            cache_dir=model_args.cache_dir,
            torch_dtype=torch_dtype,
            attn_implementation=model_args.attn_implementation,
        )

        self.model = self.model.to("cuda" if torch.cuda.is_available() else "cpu")
        self.model.eval()

        self.tokenizer = AutoTokenizer.from_pretrained(
            (
                model_args.tokenizer_name
                if model_args.tokenizer_name
                else model_args.model_name_or_path
            ),
            cache_dir=model_args.cache_dir,
            padding_side="left",
        )

        logger.info("Model loaded successfully")

    def _load_document_source(self) -> None:
        """Load document text from SQLite, local JSONL, or the legacy HF dataset."""
        if self.args.document_store:
            logger.info(f"Loading SQLite document store: {self.args.document_store}")
            self.document_store = SQLiteDocumentStore(self.args.document_store)
            logger.info(f"SQLite document store ready ({self.document_store.count()} passages)")
            return

        dataset_cache = os.getenv("HF_DATASETS_CACHE") or None

        try:
            if self.args.corpus_path:
                logger.info(f"Loading local corpus into memory: {self.args.corpus_path}")
                ds = load_dataset(
                    "json",
                    data_files=self.args.corpus_path,
                    split="train",
                    cache_dir=dataset_cache,
                )
            else:
                logger.info(f"Loading dataset: {self.args.dataset_name}")
                ds = load_dataset(
                    self.args.dataset_name, split="train", cache_dir=dataset_cache
                )

            def row_text(row):
                for key in ("text", "document_text", "contents"):
                    if key in row and row[key] is not None:
                        return row[key]
                raise KeyError("Expected one of text/document_text/contents in corpus row")

            def row_id(row):
                for key in ("docid", "id"):
                    if key in row and row[key] is not None:
                        return str(row[key])
                raise KeyError("Expected docid or id in corpus row")

            self.docid_to_text = {}
            self.docid_to_metadata = {}

            for row in ds:
                docid = row_id(row)
                text = row_text(row)

                self.docid_to_text[docid] = text

                raw_metadata = row.get("metadata") or {}
                char_count = raw_metadata.get("char_count")

                if char_count is None:
                    char_count = len(text)

                self.docid_to_metadata[docid] = {
                    "url": row.get("url"),
                    "char_count": int(char_count),
                }

            logger.info(
                f"Loaded {len(self.docid_to_text)} passages into memory "
                f"with metadata"
            )
        except Exception as e:
            source = self.args.corpus_path or self.args.dataset_name
            raise RuntimeError(f"Failed to load document source '{source}': {e}") from e

    def _get_text(self, docid: str) -> Optional[str]:
        docid = str(docid)
        if self.document_store is not None:
            return self.document_store.get(docid)
        if self.docid_to_text is not None:
            return self.docid_to_text.get(docid)
        raise RuntimeError("Document source not loaded")

    def _get_metadata(self, docid: str) -> Dict[str, Any]:
        """Return lightweight document metadata."""
        docid = str(docid)

        if self.document_store is not None:
            metadata = self.document_store.get_metadata(docid)
            if metadata is not None:
                return metadata
            return {}

        if self.docid_to_metadata is not None:
            metadata = self.docid_to_metadata.get(docid)
            if metadata is not None:
                return metadata

        # Fallback for document sources without precomputed metadata.
        text = self._get_text(docid)
        if text is None:
            return {}

        return {
            "url": None,
            "char_count": len(text),
        }

    def search_batch(
        self,
        queries: List[str],
        k: int = 10,
    ) -> List[List[Dict[str, Any]]]:
        """Search a batch of queries with one batched embedding forward pass."""
        if not all([self.retriever, self.model, self.tokenizer, self.lookup]):
            raise RuntimeError("Searcher not properly initialized")

        if not queries:
            return []

        batch_texts = [
            self.args.task_prefix + query
            for query in queries
        ]

        batch_dict = self.tokenizer(
            batch_texts,
            padding=True,
            truncation=True,
            max_length=self.args.max_length,
            return_tensors="pt",
        )

        device = "cuda" if torch.cuda.is_available() else "cpu"
        batch_dict = {
            key: value.to(device)
            for key, value in batch_dict.items()
        }

        with torch.amp.autocast(device):
            with torch.no_grad():
                q_reps = self.model.encode_query(batch_dict)
                q_reps = q_reps.cpu().detach().numpy()

        # FAISS accepts a [batch_size, embedding_dim] query matrix.
        all_scores, psg_indices = self.retriever.search(q_reps, k)

        batch_results = []

        for row_scores, row_indices in zip(all_scores, psg_indices):
            results = []

            for score, index in zip(row_scores, row_indices):
                # IVF may return -1 when the probed lists contain fewer than k
                # candidates. Skip invalid ids instead of indexing lookup[-1].
                index = int(index)
                if index < 0 or index >= len(self.lookup):
                    continue

                passage_id = self.lookup[index]
                passage_text = self._get_text(passage_id) or "Text not found"

                results.append(
                    {
                        "docid": passage_id,
                        "score": float(score),
                        "text": passage_text,
                        "metadata": self._get_metadata(passage_id),
                    }
                )

            batch_results.append(results)

        return batch_results

    def search(self, query: str, k: int = 10) -> List[Dict[str, Any]]:
        """Backward-compatible single-query search."""
        return self.search_batch([query], k)[0]


    def get_document(self, docid: str) -> Optional[Dict[str, Any]]:
        text = self._get_text(docid)
        if text is None:
            return None

        return {
            "docid": docid,
            "text": text,
        }

    @property
    def search_type(self) -> str:
        return "FAISS"


class ReasonIrSearcher(FaissSearcher):
    def _load_model(self) -> None:
        logger.info(f"Loading model: {self.args.model_name}")

        hf_home = os.getenv("HF_HOME")
        if hf_home:
            cache_dir = hf_home
        else:
            cache_dir = None

        model_args = ModelArguments(
            model_name_or_path=self.args.model_name,
            normalize=self.args.normalize,
            pooling=self.args.pooling,
            cache_dir=cache_dir,
        )

        if self.args.torch_dtype == "float16":
            torch_dtype = torch.float16
        elif self.args.torch_dtype == "bfloat16":
            torch_dtype = torch.bfloat16
        else:
            torch_dtype = torch.float32

        self.model = AutoModel.from_pretrained(
            model_args.model_name_or_path,
            cache_dir=model_args.cache_dir,
            torch_dtype=torch_dtype,
            trust_remote_code=True,
        )
        self.model = self.model.to("cuda" if torch.cuda.is_available() else "cpu")
        self.model.eval()

        logger.info("Model loaded successfully")

    def search(self, query: str, k: int = 10) -> List[Dict[str, Any]]:
        if not all([self.retriever, self.model, self.lookup]):
            raise RuntimeError("Searcher not properly initialized")

        device = "cuda" if torch.cuda.is_available() else "cpu"

        with torch.amp.autocast(device):
            with torch.no_grad():
                q_reps = self.model.encode(
                    [query],
                    instruction="<|user|>\nGiven a question, retrieve relevant passages that help answer the question\n<|embed|>\n",
                )

        all_scores, psg_indices = self.retriever.search(q_reps, k)

        results = []
        for score, index in zip(all_scores[0], psg_indices[0]):
            passage_id = self.lookup[index]
            passage_text = self._get_text(passage_id) or "Text not found"

            results.append(
                {"docid": passage_id, "score": float(score), "text": passage_text}
            )

        return results
