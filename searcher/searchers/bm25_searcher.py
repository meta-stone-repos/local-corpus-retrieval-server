"""
BM25 searcher implementation using Pyserini.
"""

import json
import logging
from typing import Any, Dict, Optional

from pyserini.search.lucene import LuceneSearcher

from .base import BaseSearcher
from .document_store import SQLiteDocumentStore

logger = logging.getLogger(__name__)


class BM25Searcher(BaseSearcher):
    @classmethod
    def parse_args(cls, parser):
        parser.add_argument(
            "--index-path",
            required=False,
            help="Name or path of Lucene index (e.g. msmarco-v1-passage). Required unless --corpus supplies it via a manifest.",
        )

        parser.add_argument(
            "--document-store",
            default=None,
            help=(
                "Optional local SQLite document store generated by "
                "build_corpus.py for document text and metadata lookup."
            ),
        )

    def __init__(self, args):
        if not args.index_path:
            raise ValueError("index_path is required for BM25 searcher")

        self.args = args
        self.searcher = None
        self.document_store = None

        logger.info(f"Initializing BM25 searcher with index: {args.index_path}")

        try:
            self.searcher = LuceneSearcher(args.index_path)
        except Exception as exc:
            raise ValueError(
                f"Index '{args.index_path}' is not a valid local Lucene index path."
            ) from exc

        if getattr(args, "document_store", None):
            logger.info(
                f"Loading SQLite document store: {args.document_store}"
            )
            self.document_store = SQLiteDocumentStore(
                args.document_store
            )
            logger.info(
                f"SQLite document store ready "
                f"({self.document_store.count()} passages)"
            )

        logger.info("BM25 searcher initialized successfully")

    def search(self, query: str, k: int = 10) -> list[dict[str, Any]]:
        if not self.searcher:
            raise RuntimeError("Searcher not initialized")

        hits = self.searcher.search(query, k)

        metadata_by_docid = {}
        if self.document_store is not None:
            metadata_by_docid = self.document_store.get_metadata_batch(
                [str(hit.docid) for hit in hits]
            )

        results = []

        for hit in hits:
            raw = json.loads(hit.lucene_document.get("raw"))
            text = raw["contents"]

            metadata = {
                "url": None,
                "char_count": len(text),
            }

            if self.document_store is not None:
                stored_metadata = metadata_by_docid.get(str(hit.docid))

                if stored_metadata is not None:
                    metadata = stored_metadata

                    if metadata.get("char_count") is None:
                        metadata["char_count"] = len(text)

            results.append(
                {
                    "docid": hit.docid,
                    "score": hit.score,
                    "text": text,
                    "metadata": metadata,
                }
            )

        return results

    def get_document(self, docid: str) -> Optional[Dict[str, Any]]:
        if not self.searcher:
            raise RuntimeError("Searcher not initialized")

        if self.document_store is not None:
            return self.document_store.get_document(docid)

        doc = self.searcher.doc(docid)
        if doc is None:
            return None

        return {
            "docid": docid,
            "text": json.loads(doc.raw())["contents"],
        }

    @property
    def search_type(self) -> str:
        return "BM25"
